def alt_cell(index: int, m: dict, fg: str) -> str:
    ox = index * m["pitch"]
    kind = ("mascot", "name", "slogan")[index % 3]
    cy = H / 2
    if kind == "mascot":
        x = ox + (m["pitch"] - m["jelly_w"]) / 2
        jy = (H - m["jelly_h"]) / 2
        return jelly_group(x, jy, m["jelly_h"], fg)
    if kind == "name":
        x = ox + (m["pitch"] - m["word_w"]) / 2
        word_top = cy - m["word_h"] / 2
        u_y = word_top - m["umin"]
        i_y = word_top + (m["umax"] - m["umin"]) + m["word_gap"] - m["imin"]
        return "\n".join(
            [
                path_at(m["u_d"], x, u_y, fg),
                path_at(m["i_d"], x, i_y, fg),
            ]
        )
    tag = m["tags"][CLUB_BEATS[index // 3]["tag"]]
    copy_w = max(tag["adv"], m["url_adv"])
    x = ox + (m["pitch"] - copy_w) / 2
    rule_h = 0.28
    gap_tag_rule = 0.85
    gap_rule_url = 0.88
    stack_h = (
        (tag["tmax"] - tag["tmin"])
        + gap_tag_rule
        + rule_h
        + gap_rule_url
        + (m["rmax"] - m["rmin"])
    )
    tag_y = cy - stack_h / 2 - tag["tmin"]
    rule_y = tag_y + tag["tmax"] + gap_tag_rule
    url_y = rule_y + rule_h + gap_rule_url - m["rmin"]
    return "\n".join(
        [
            path_at(tag["d"], x, tag_y, fg),
            f'    <rect x="{x:.3f}" y="{rule_y:.3f}" width="{copy_w:.3f}" '
            f'height="{rule_h}" fill="{fg}"/>',
            path_at(m["url_d"], x, url_y, fg),
        ]
    )


def alt_tiles(m: dict, fg: str, *, count: int | None = None) -> str:
    n = m["count"] if count is None else count
    return "\n".join(alt_cell(i, m, fg) for i in range(n))


