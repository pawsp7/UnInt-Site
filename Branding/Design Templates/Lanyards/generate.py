def rail_at(h: float) -> float:
    return RAIL * (h / H)


def dim_label(h: float) -> str:
    cm = h / 10.0
    h_txt = f"{int(cm)}cm" if cm == int(cm) else f"{cm:g}cm"
    return f"45cm × {h_txt}"


def scale_around(inner: str, ox: float, pitch: float, h: float) -> str:
    """Scale a 20 mm tile uniformly onto height h, keeping pitch and x origin."""
    if h == H:
        return inner
    s = h / H
    cx = ox + pitch / 2
    return (
        f'    <g transform="translate({cx:.3f} {h / 2:.3f}) scale({s:.6f}) '
        f'translate({-cx:.3f} {-H / 2:.3f})">\n'
        f"{inner}\n"
        "    </g>"
    )


def scale_in_place(inner: str, ox: float, pitch: float, s: float) -> str:
    """Uniformly scale a 20 mm tile about its pitch centre, staying on the 20 mm strap."""
    if s == 1:
        return inner
    cx = ox + pitch / 2
    cy = H / 2
    return (
        f'    <g transform="translate({cx:.3f} {cy:.3f}) scale({s:.6f}) '
        f'translate({-cx:.3f} {-cy:.3f})">\n'
        f"{inner}\n"
        "    </g>"
    )


def rail_content_scale(rail: float) -> float:
    """Scale art so the original gap outside 1.25 mm rails is kept for a thicker rail."""
    old_gap = SAFE - RAIL
    new_inset = rail + old_gap
    return (H / 2 - new_inset) / (H / 2 - SAFE)


