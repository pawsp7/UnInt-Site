class Font:
    def __init__(self, path: Path):
        self.tt = TTFont(path)
        self.gs = self.tt.getGlyphSet()
        self.cmap = self.tt.getBestCmap()
        self.upem = self.tt["head"].unitsPerEm

    def shape(
        self, text: str, size: float, *, tracking: float = 0, scale_x: float = 1.0
    ):
        s = size / self.upem
        x = 0.0
        chunks: list[str] = []
        for ch in text:
            if ch == " ":
                space = self.gs[self.cmap.get(ord(" "), "space")]
                x += space.width * s * scale_x + tracking
                continue
            name = self.cmap.get(ord(ch))
            if name is None:
                x += size * 0.45 * scale_x
                continue
            g = self.gs[name]
            pen = SVGPathPen(self.gs)
            tpen = TransformPen(pen, (s * scale_x, 0, 0, -s, x, 0))
            g.draw(tpen)
            d = round_path(pen.getCommands())
            if d:
                chunks.append(d)
            x += g.width * s * scale_x + tracking
        return " ".join(chunks), x

    def ink_bounds(
        self, text: str, size: float, *, tracking: float = 0, scale_x: float = 1.0
    ) -> tuple[float, float, float, float, float]:
        s = size / self.upem
        x = 0.0
        minx = miny = 1e9
        maxx = maxy = -1e9
        for ch in text:
            if ch == " ":
                space = self.gs[self.cmap.get(ord(" "), "space")]
                x += space.width * s * scale_x + tracking
                continue
            name = self.cmap.get(ord(ch))
            if name is None:
                x += size * 0.45 * scale_x
                continue
            g = self.gs[name]
            pen = BoundsPen(self.gs)
            tpen = TransformPen(pen, (s * scale_x, 0, 0, -s, x, 0))
            g.draw(tpen)
            if pen.bounds:
                a, b, c, d = pen.bounds
                minx, miny = min(minx, a), min(miny, b)
                maxx, maxy = max(maxx, c), max(maxy, d)
            x += g.width * s * scale_x + tracking
        if minx > maxx:
            return 0.0, -size * 0.72, x, 0.0, x
        return minx, miny, maxx, maxy, x


def round_path(d: str) -> str:
    def repl(m: re.Match) -> str:
        n = float(m.group(0))
        r = round(n, 2)
        if r == int(r):
            return str(int(r))
        return f"{r:.2f}".rstrip("0").rstrip(".")

    return re.sub(r"-?\d+\.?\d*(?:e-?\d+)?", repl, d, flags=re.I)


