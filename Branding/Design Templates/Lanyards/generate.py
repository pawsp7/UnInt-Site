def restart_mark(cx: float, cy: float, r: float, color: str, stroke: float) -> str:
    """Clockwise refresh arrow from the vector kit, one colour."""
    a0 = math.radians(32)
    a1 = math.radians(322)
    x0 = cx + r * math.cos(a0)
    y0 = cy + r * math.sin(a0)
    x1 = cx + r * math.cos(a1)
    y1 = cy + r * math.sin(a1)
    tx, ty = -math.sin(a1), math.cos(a1)
    px, py = -ty, tx
    head_len = stroke * 2.6
    head_w = stroke * 1.55
    arc = (
        f'<path d="M{x0:.2f} {y0:.2f} A {r:.2f} {r:.2f} 0 1 1 {x1:.2f} {y1:.2f}" '
        f'fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round"/>'
    )
    tip_x = x1 + tx * head_len * 0.55
    tip_y = y1 + ty * head_len * 0.55
    b1x, b1y = x1 + px * head_w, y1 + py * head_w
    b2x, b2y = x1 - px * head_w, y1 - py * head_w
    head = (
        f'<polygon points="{tip_x:.2f},{tip_y:.2f} {b1x:.2f},{b1y:.2f} '
        f'{b2x:.2f},{b2y:.2f}" fill="{color}"/>'
    )
    return arc + head


