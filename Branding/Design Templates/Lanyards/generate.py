def unit_artwork(p: dict, m: dict, *, jelly_fill: str, ox: float = 0.0) -> str:
    cy = H / 2
    x = ox + m["pad"]
    jy = (H - m["jelly_h"]) / 2
    parts = [jelly_group(x, jy, m["jelly_h"], jelly_fill)]
    x += m["jelly_w"] + m["gaps"]["jelly_word"]

    word_top = cy - m["word_h"] / 2
    u_y = word_top - m["umin"]
    i_y = word_top + (m["umax"] - m["umin"]) + m["word_gap"] - m["imin"]
    parts.append(path_at(m["u_d"], x, u_y, PAPER))
    parts.append(path_at(m["i_d"], x, i_y, PAPER))
    x += m["word_w"] + m["gaps"]["word_bars"]

    bar_x = x
    lime_h, pink_h, bar_gap = 1.08, 1.08, 0.9
    bars_h = lime_h + bar_gap + pink_h
    by = cy - bars_h / 2
    parts.append(
        f'    <rect x="{bar_x:.3f}" y="{by:.3f}" width="6.6" height="{lime_h}" '
        f'rx="0.45" fill="{LIME}"/>'
    )
    parts.append(
        f'    <rect x="{bar_x:.3f}" y="{by + lime_h + bar_gap:.3f}" width="4.4" '
        f'height="{pink_h}" rx="0.45" fill="{PINK}"/>'
    )
    x += m["bars_w"] + m["gaps"]["bars_name"]

    rule_h = 0.28
    gap_name_rule = 0.95
    gap_rule_role = 0.98
    stack_h = (
        (p["nmax"] - p["nmin"])
        + gap_name_rule
        + rule_h
        + gap_rule_role
        + (p["rmax"] - p["rmin"])
    )
    origin_y = cy - stack_h / 2 - p["nmin"]
    name_y = origin_y
    rule_y = name_y + p["nmax"] + gap_name_rule
    role_y = rule_y + rule_h + gap_rule_role - p["rmin"]
    rule_w = max(p["name_adv"], p["role_adv"])
    parts.append(path_at(p["name_d"], x, name_y, LIME))
    parts.append(
        f'    <rect x="{x:.3f}" y="{rule_y:.3f}" width="{rule_w:.3f}" '
        f'height="{rule_h}" fill="{LIME}"/>'
    )
    parts.append(path_at(p["role_d"], x, role_y, PINK))
    x += m["person_w"] + m["gaps"]["name_pill"]

    py = cy - m["pill_h"] / 2
    tick_w = 0.8
    parts.append(
        f'    <rect x="{x:.3f}" y="{py:.3f}" width="{m["pill_w"]:.3f}" '
        f'height="{m["pill_h"]:.3f}" rx="1.05" fill="{LIME}"/>'
    )
    parts.append(
        f'    <rect x="{x + 0.7:.3f}" y="{py + m["pill_h"] * 0.22:.3f}" '
        f'width="{tick_w:.3f}" height="{m["pill_h"] * 0.56:.3f}" rx="0.2" '
        f'fill="{INK}"/>'
    )
    exec_x = x + m["pill_pad_x"] + 0.45
    exec_y = cy - (m["emin"] + m["emax"]) / 2
    parts.append(path_at(m["exec_d"], exec_x, exec_y, INK))
    return "\n".join(parts)


