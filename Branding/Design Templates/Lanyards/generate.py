def mm_to_px(mm: float, dpi: int = 300) -> int:
    return max(1, round(mm / 25.4 * dpi))


def rasterize(svg_text: str, dest: Path, *, width_mm: float) -> None:
    import cairosvg
    from PIL import Image

    width = mm_to_px(width_mm)
    raw = cairosvg.svg2png(bytestring=svg_text.encode("utf-8"), output_width=width)
    im = Image.open(io.BytesIO(raw))
    dest.parent.mkdir(parents=True, exist_ok=True)
    if im.mode not in {"RGB", "RGBA"}:
        im = im.convert("RGBA" if "A" in im.getbands() else "RGB")
    im.save(dest, "PNG", optimize=True, dpi=(300, 300))


